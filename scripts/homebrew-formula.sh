#!/bin/sh
# Print the Homebrew formula for a published release.
#
#   scripts/homebrew-formula.sh v0.14.0 > Formula/neboto.rb
#   scripts/homebrew-formula.sh v0.14.0 path/to/sha256-dir > Formula/neboto.rb
#
# The formula installs the prebuilt release archives (no build from source),
# one per OS × arch, so it needs the four neboto-<target>.sha256 assets. With
# a directory it reads them from there; without one it downloads them from
# the release with `gh`. Run by the Release workflow's `homebrew` job, which
# pushes the result to neboto/homebrew-tap; run it by hand to fix the tap up
# after a release cut with scripts/release-local.sh.
#
# The archive names are the same load-bearing <bin>-<target>.tar.gz that
# install.sh and the binstall table use (docs/RELEASING.md).
set -eu

tag="${1:?usage: homebrew-formula.sh <tag> [sha256-dir]}"
dir="${2:-}"
repo="neboto/neboto-tui"

die() { printf 'error: %s\n' "$*" >&2; exit 1; }

case "$tag" in v[0-9]*.[0-9]*.[0-9]*) ;; *) die "tag must look like v0.1.0" ;; esac
case "$tag" in *-*) die "$tag is a prerelease; the tap only follows stable releases" ;; esac
# No `version` line in the formula: brew scans it from the URL's /v0.14.0/
# path, and `brew audit --strict` rejects an explicit one as redundant.

if [ -z "$dir" ]; then
  dir="$(mktemp -d)"
  trap 'rm -rf "$dir"' EXIT
  gh release download "$tag" --repo "$repo" --pattern 'neboto-*.sha256' --dir "$dir" >/dev/null
fi

sha() { # target → the archive's sha256, checked to be 64 hex chars
  f="$dir/neboto-$1.sha256"
  [ -f "$f" ] || die "no $f"
  s="$(awk -v a="neboto-$1.tar.gz" '$2 == a || $2 == "*" a { print $1 }' "$f")"
  printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$' || die "no sha256 for neboto-$1.tar.gz in $f"
  printf '%s' "$s"
}

url="https://github.com/$repo/releases/download/$tag"
mac_arm="$(sha aarch64-apple-darwin)"
mac_intel="$(sha x86_64-apple-darwin)"
linux_arm="$(sha aarch64-unknown-linux-gnu)"
linux_intel="$(sha x86_64-unknown-linux-gnu)"

cat <<EOF
# Generated by scripts/homebrew-formula.sh in neboto/neboto-tui for $tag.
# Don't edit by hand: the Release workflow rewrites this file on every release.
class Neboto < Formula
  desc "Fast, keyboard-driven, read-only terminal UI for browsing AWS"
  homepage "https://neboto.dev"
  license "MIT"

  on_macos do
    on_arm do
      url "$url/neboto-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$url/neboto-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  # The Linux builds need glibc 2.35 or newer (they're built on Ubuntu 22.04).
  on_linux do
    on_arm do
      url "$url/neboto-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$url/neboto-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "neboto"
    pkgshare.install "config.example.toml"
    doc.install "PERMISSIONS.md"
  end

  def caveats
    <<~EOS
      neboto uses your AWS CLI profiles (~/.aws/config). An example config is at
        #{pkgshare}/config.example.toml
      Copy it to ~/.neboto.toml to change the defaults.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/neboto --version")
  end
end
EOF
